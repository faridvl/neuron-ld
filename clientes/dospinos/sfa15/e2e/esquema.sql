-- ## Bases LDCOM en el Docker
SELECT name FROM sys.databases WHERE name LIKE 'LDCOM%' ORDER BY name
-- ## Columnas de Cliente_Relacion
SELECT COLUMN_NAME, DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'Cliente_Relacion' ORDER BY ORDINAL_POSITION
-- ## Columnas de Cliente (activo, bloqueo, banca, interfaz)
SELECT COLUMN_NAME, DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'Cliente' AND (COLUMN_NAME LIKE '%Activ%' OR COLUMN_NAME LIKE '%Bloq%' OR COLUMN_NAME LIKE '%Banca%' OR COLUMN_NAME LIKE '%Interfaz%' OR COLUMN_NAME LIKE 'Tipo_Id' OR COLUMN_NAME LIKE 'Cliente_Nombre')
-- ## Tablas de planes de financiamiento
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME LIKE 'Plan%Financ%' ORDER BY TABLE_NAME
-- ## Columnas de esas tablas
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME LIKE 'Plan%Financ%' ORDER BY TABLE_NAME, ORDINAL_POSITION
